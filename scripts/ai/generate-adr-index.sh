#!/usr/bin/env bash
# Regenerates docs/ai/adr-index.md from every DECISIONS.md file's own ADR headings/Status lines.
# Purely mechanical (no manual metadata) — see scripts/architecture/DECISIONS.md ADR-001 for the rationale.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUTPUT="$REPO_ROOT/docs/ai/adr-index.md"

{
  echo "# ADR index (generated)"
  echo
  echo "Generated by \`scripts/ai/generate-adr-index.sh\` from every \`DECISIONS.md\` file's own"
  echo "\`## ADR-NNN: Title\` heading and the \`**Status:**\` block beneath it — do not hand-edit,"
  echo "rerun the script after any \`DECISIONS.md\` change instead. Only files using the"
  echo "\`## ADR-NNN:\` numbering convention are indexed; see \"Known gaps\" below for the rest. An"
  echo "optional \`**Also affects:** module-a, module-b\` line right after \`**Status:**\` cross-lists"
  echo "an ADR under other modules too — one extra row per affected module, same ADR, same file."
  echo
  echo "| ADR | Module | Status | Title |"
  echo "|---|---|---|---|"
} > "$OUTPUT"

gaps=""
while IFS= read -r -d '' file; do
  rel="${file#"$REPO_ROOT"/}"
  module="$(dirname "$rel")"
  rows_before=$(wc -l < "$OUTPUT")
  awk -v module="$module" '
    { sub(/\r$/, "") }
    function flush() {
      if (adr == "") return
      if (state >= 2) {
        printf("| %s (%s) | %s | %s | %s |\n", adr, module, module, status, title)
        if (affects != "") {
          n = split(affects, mods, ",")
          for (i = 1; i <= n; i++) {
            m = mods[i]
            gsub(/^[ \t]+|[ \t]+$/, "", m)
            if (m != "") printf("| %s (%s) | %s | %s | %s |\n", adr, module, m, status, title)
          }
        }
      } else {
        print "WARN: " module ": " adr " has no **Status:** line, skipped" > "/dev/stderr"
      }
    }
    /^## ADR-[0-9]+:/ {
      flush()
      line = $0
      sub(/^## /, "", line)
      split(line, parts, ": ")
      adr = parts[1]
      title = line
      sub(/^[^:]+: /, "", title)
      status = ""
      affects = ""
      state = 1
      next
    }
    state == 1 && /^\*\*Status:\*\*/ {
      status = $0
      sub(/^\*\*Status:\*\* */, "", status)
      state = 2
      next
    }
    state == 1 && /^[[:space:]]*$/ { next }
    state == 1 { title = title " " $0; next }
    state == 2 && /^[[:space:]]*$/ { state = 3; next }
    state == 2 { status = status " " $0; next }
    # "**Also affects:** module-a, module-b" -- optional, only checked on the first non-blank line
    # right after the Status paragraph. Cross-lists this ADR under other modules'"'"' pages without
    # duplicating its text (see scripts/architecture/DECISIONS.md for the design this supports).
    state == 3 && /^[[:space:]]*$/ { next }
    state == 3 && /^\*\*Also affects:\*\*/ {
      affects = $0
      sub(/^\*\*Also affects:\*\* */, "", affects)
      flush(); adr = ""; state = 0; next
    }
    state == 3 { flush(); adr = ""; state = 0; next }
    END { flush() }
  ' "$file" >> "$OUTPUT"
  rows_after=$(wc -l < "$OUTPUT")
  if [ "$rows_after" -eq "$rows_before" ]; then
    gaps="$gaps- \`$rel\` — no \`## ADR-NNN:\` heading found (non-standard format); not indexed\n"
  fi
done < <(find "$REPO_ROOT" -name "DECISIONS.md" -not -path "*/target/*" -print0 | sort -z)

if [ -n "$gaps" ]; then
  {
    echo
    echo "## Known gaps"
    echo
    echo "$gaps"
  } >> "$OUTPUT"
fi

count=$(grep -c '^| ADR-' "$OUTPUT" || true)
echo "Wrote $count entries to $OUTPUT"
[ -n "$gaps" ] && printf '%b' "Gaps (not indexed):\n$gaps"
exit 0
