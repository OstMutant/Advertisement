#!/usr/bin/env bash
# ── Header ──────────────────────────────────────────────────────────────────
# Description: Regenerates .claude/nav/adr-index.md from every DECISIONS.md file's own ADR
#   headings/Status lines -- purely mechanical, no manual metadata. See .claude/nav/adr-index.md.
# Usage: bash .claude/nav/scripts/generate-adr-index.sh
# Uses: bash, awk, find.
# Env: None.
# Input: every DECISIONS.md file in the repo (only files using the "## ADR-NNN:" numbering
#   convention are indexed).
# Outputs: overwrites .claude/nav/adr-index.md; a WARN line to stderr per ADR with no **Status:**
#   line; a "## Known gaps" section listing any DECISIONS.md file with no "## ADR-NNN:" heading.
# Returns: 0 always.
# ────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUTPUT="$REPO_ROOT/.claude/nav/adr-index.md"

{
  echo "# ADR index (generated)"
  echo
  echo "Generated by \`.claude/nav/scripts/generate-adr-index.sh\` from every \`DECISIONS.md\` file's own"
  echo "\`## ADR-NNN: Title\` heading and the \`**Status:**\` block beneath it — do not hand-edit,"
  echo "rerun the script after any \`DECISIONS.md\` change instead. Only files using the"
  echo "\`## ADR-NNN:\` numbering convention are indexed; see \"Known gaps\" below for the rest. Two"
  echo "optional lines may follow \`**Status:**\`, in this order: \`**Verified:** YYYY-MM-DD\` (the"
  echo "last time anyone actually confirmed this entry's claim still matches the real code — stamped"
  echo "lazily, whenever it happens to be confirmed as a side effect of other work, never a dedicated"
  echo "audit pass) and \`**Also affects:** module-a, module-b\` (cross-lists an ADR under other"
  echo "modules too — one extra row per affected module, same ADR, same file). Blank in the"
  echo "\`Verified\` column means never independently re-confirmed since the entry was written."
  echo
  echo "| ADR | Module | Status | Verified | Title |"
  echo "|---|---|---|---|---|"
} > "$OUTPUT"

gaps=""
while IFS= read -r -d '' file; do
  rel="${file#"$REPO_ROOT"/}"
  module="$(dirname "$rel")"
  rows_before=$(wc -l < "$OUTPUT")
  awk -v module="$module" '
    { sub(/\r$/, "") }
    function flush() {
      if (adr == "") return
      if (state >= 2) {
        printf("| %s (%s) | %s | %s | %s | %s |\n", adr, module, module, status, verified, title)
        if (affects != "") {
          n = split(affects, mods, ",")
          for (i = 1; i <= n; i++) {
            m = mods[i]
            gsub(/^[ \t]+|[ \t]+$/, "", m)
            if (m != "") printf("| %s (%s) | %s | %s | %s | %s |\n", adr, module, m, status, verified, title)
          }
        }
      } else {
        print "WARN: " module ": " adr " has no **Status:** line, skipped" > "/dev/stderr"
      }
    }
    /^## ADR-[0-9]+:/ {
      flush()
      line = $0
      sub(/^## /, "", line)
      split(line, parts, ": ")
      adr = parts[1]
      title = line
      sub(/^[^:]+: /, "", title)
      status = ""
      verified = ""
      affects = ""
      state = 1
      next
    }
    state == 1 && /^\*\*Status:\*\*/ {
      status = $0
      sub(/^\*\*Status:\*\* */, "", status)
      state = 2
      next
    }
    state == 1 && /^[[:space:]]*$/ { next }
    state == 1 { title = title " " $0; next }
    state == 2 && /^[[:space:]]*$/ { state = 3; next }
    state == 2 { status = status " " $0; next }
    # Two optional metadata lines, in order, right after the blank line following the Status
    # paragraph: "**Verified:** YYYY-MM-DD" (last real-code confirmation date, stamped lazily --
    # see .claude/rules.md) then "**Also affects:** module-a, module-b" (cross-lists this ADR
    # under other modules pages without duplicating its text -- see
    # docs/architecture/scripts/DECISIONS.md for the design this supports).
    state == 3 && /^[[:space:]]*$/ { next }
    state == 3 && /^\*\*Verified:\*\*/ {
      verified = $0
      sub(/^\*\*Verified:\*\* */, "", verified)
      state = 4
      next
    }
    state == 3 && /^\*\*Also affects:\*\*/ {
      affects = $0
      sub(/^\*\*Also affects:\*\* */, "", affects)
      flush(); adr = ""; state = 0; next
    }
    state == 3 { flush(); adr = ""; state = 0; next }
    state == 4 && /^[[:space:]]*$/ { next }
    state == 4 && /^\*\*Also affects:\*\*/ {
      affects = $0
      sub(/^\*\*Also affects:\*\* */, "", affects)
      flush(); adr = ""; state = 0; next
    }
    state == 4 { flush(); adr = ""; state = 0; next }
    END { flush() }
  ' "$file" >> "$OUTPUT"
  rows_after=$(wc -l < "$OUTPUT")
  if [ "$rows_after" -eq "$rows_before" ]; then
    gaps="$gaps- \`$rel\` — no \`## ADR-NNN:\` heading found (non-standard format); not indexed\n"
  fi
done < <(find "$REPO_ROOT" -name "DECISIONS.md" -not -path "*/target/*" -print0 | sort -z)

if [ -n "$gaps" ]; then
  {
    echo
    echo "## Known gaps"
    echo
    echo "$gaps"
  } >> "$OUTPUT"
fi

count=$(grep -c '^| ADR-' "$OUTPUT" || true)
echo "Wrote $count entries to $OUTPUT"
[ -n "$gaps" ] && printf '%b' "Gaps (not indexed):\n$gaps"
exit 0
