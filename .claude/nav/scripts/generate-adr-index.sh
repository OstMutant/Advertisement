#!/usr/bin/env bash
# ── Header ──────────────────────────────────────────────────────────────────
# Description: Regenerates .claude/nav/adr-index.md from every DECISIONS.md file's own ADR
#   headings/Status lines, plus a Referenced count tallied from every task file's own
#   "adrs_referenced:" Operational-notes line -- purely mechanical, no manual metadata. See
#   .claude/nav/adr-index.md.
# Usage: bash .claude/nav/scripts/generate-adr-index.sh [OUTPUT_PATH]
#   OUTPUT_PATH  where to write the index (default .claude/nav/adr-index.md) -- the freshness
#                check passes a throwaway temp path here so it never rewrites the committed file.
# Uses: bash, awk, find, grep.
# Env: None.
# Input: every DECISIONS.md file in the repo (only files using the "## ADR-NNN:" numbering
#   convention are indexed); every "- adrs_referenced: ..." line in backlog/tasks/*.md and
#   backlog/completed/tasks/*.md.
# Outputs: writes OUTPUT_PATH atomically -- generated into a temp sibling, moved into place only
#   on full success, so an interrupted run never leaves a partial or empty file, then chmod 644 (the
#   temp sibling is mktemp-created 0600; the committed index must stay world-readable so CI's
#   working-tree sync can read it); a WARN line to stderr per ADR with no **Status:** line; a
#   "## Known gaps" section listing any DECISIONS.md file with no "## ADR-NNN:" heading.
# Returns: 0 always.
# ────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUTPUT="${1:-$REPO_ROOT/.claude/nav/adr-index.md}"
WORK="$(mktemp "${OUTPUT}.XXXXXX.tmp")"
TALLY="$(mktemp "${OUTPUT}.XXXXXX.tally.tmp")"
trap 'rm -f "$WORK" "$TALLY"' EXIT

# Tally how many task files cite each "ADR-NNN (module)" key via its own Operational-notes
# "adrs_referenced:" line -- same key shape as this script's own first column, so the two join
# without reformatting. Comma-separated, "n/a" and blanks ignored.
{ { grep -h -o 'adrs_referenced:.*' "$REPO_ROOT"/backlog/tasks/*.md "$REPO_ROOT"/backlog/completed/tasks/*.md 2>/dev/null || true; } \
  | sed 's/^adrs_referenced: *//' \
  | tr ',' '\n' \
  | sed 's/^ *//; s/ *$//' \
  | { grep -v '^n\/a$' || true; } \
  | { grep -v '^$' || true; } \
  | sort | uniq -c \
  | awk '{count=$1; $1=""; key=$0; sub(/^ /, "", key); printf("%s\t%s\n", key, count)}'; } \
  > "$TALLY"

{
  echo "# ADR index (generated)"
  echo
  echo "Generated by \`.claude/nav/scripts/generate-adr-index.sh\` from every \`DECISIONS.md\` file's own"
  echo "\`## ADR-NNN: Title\` heading and the \`**Status:**\` block beneath it — do not hand-edit,"
  echo "rerun the script after any \`DECISIONS.md\` change instead. Only files using the"
  echo "\`## ADR-NNN:\` numbering convention are indexed; see \"Known gaps\" below for the rest. Two"
  echo "optional lines may follow \`**Status:**\`, in this order: \`**Verified:** YYYY-MM-DD\` (the"
  echo "last time anyone actually confirmed this entry's claim still matches the real code — stamped"
  echo "lazily, whenever it happens to be confirmed as a side effect of other work, never a dedicated"
  echo "audit pass) and \`**Also affects:** module-a, module-b\` (cross-lists an ADR under other"
  echo "modules too — one extra row per affected module, same ADR, same file). Blank in the"
  echo "\`Verified\` column means never independently re-confirmed since the entry was written."
  echo "\`Referenced\` tallies every task file's own \`adrs_referenced:\` Operational-notes line citing"
  echo "this exact \`ADR-NNN (module)\` key — 0 means no task has cited it that way yet, not"
  echo "necessarily that it's unused."
  echo
  echo "| ADR | Module | Status | Verified | Referenced | Title |"
  echo "|---|---|---|---|---|---|"
} > "$WORK"

gaps=""
while IFS= read -r -d '' file; do
  rel="${file#"$REPO_ROOT"/}"
  module="$(dirname "$rel")"
  rows_before=$(wc -l < "$WORK")
  awk -v module="$module" -v tally_file="$TALLY" '
    BEGIN {
      while ((getline tline < tally_file) > 0) {
        split(tline, tparts, "\t")
        refcount[tparts[1]] = tparts[2]
      }
      close(tally_file)
    }
    { sub(/\r$/, "") }
    function refs(key) { return (key in refcount) ? refcount[key] : 0 }
    function flush() {
      if (adr == "") return
      if (state >= 2) {
        key = adr " (" module ")"
        printf("| %s (%s) | %s | %s | %s | %s | %s |\n", adr, module, module, status, verified, refs(key), title)
        if (affects != "") {
          n = split(affects, mods, ",")
          for (i = 1; i <= n; i++) {
            m = mods[i]
            gsub(/^[ \t]+|[ \t]+$/, "", m)
            if (m != "") {
              mkey = adr " (" m ")"
              printf("| %s (%s) | %s | %s | %s | %s | %s |\n", adr, module, m, status, verified, refs(mkey), title)
            }
          }
        }
      } else {
        print "WARN: " module ": " adr " has no **Status:** line, skipped" > "/dev/stderr"
      }
    }
    /^## ADR-[0-9]+:/ {
      flush()
      line = $0
      sub(/^## /, "", line)
      split(line, parts, ": ")
      adr = parts[1]
      title = line
      sub(/^[^:]+: /, "", title)
      status = ""
      verified = ""
      affects = ""
      state = 1
      next
    }
    state == 1 && /^\*\*Status:\*\*/ {
      status = $0
      sub(/^\*\*Status:\*\* */, "", status)
      state = 2
      next
    }
    state == 1 && /^[[:space:]]*$/ { next }
    state == 1 { title = title " " $0; next }
    state == 2 && /^[[:space:]]*$/ { state = 3; next }
    state == 2 { status = status " " $0; next }
    # Two optional metadata lines, in order, right after the blank line following the Status
    # paragraph: "**Verified:** YYYY-MM-DD" (last real-code confirmation date, stamped lazily --
    # see .claude/rules.md) then "**Also affects:** module-a, module-b" (cross-lists this ADR
    # under other modules pages without duplicating its text -- see
    # docs/architecture/scripts/DECISIONS.md for the design this supports).
    state == 3 && /^[[:space:]]*$/ { next }
    state == 3 && /^\*\*Verified:\*\*/ {
      verified = $0
      sub(/^\*\*Verified:\*\* */, "", verified)
      state = 4
      next
    }
    state == 3 && /^\*\*Also affects:\*\*/ {
      affects = $0
      sub(/^\*\*Also affects:\*\* */, "", affects)
      flush(); adr = ""; state = 0; next
    }
    state == 3 { flush(); adr = ""; state = 0; next }
    state == 4 && /^[[:space:]]*$/ { next }
    state == 4 && /^\*\*Also affects:\*\*/ {
      affects = $0
      sub(/^\*\*Also affects:\*\* */, "", affects)
      flush(); adr = ""; state = 0; next
    }
    state == 4 { flush(); adr = ""; state = 0; next }
    END { flush() }
  ' "$file" >> "$WORK"
  rows_after=$(wc -l < "$WORK")
  if [ "$rows_after" -eq "$rows_before" ]; then
    gaps="$gaps- \`$rel\` — no \`## ADR-NNN:\` heading found (non-standard format); not indexed\n"
  fi
done < <(find "$REPO_ROOT" -name "DECISIONS.md" -not -path "*/target/*" -not -path "*/.claude/worktrees/*" -print0 | sort -z)

if [ -n "$gaps" ]; then
  {
    echo
    echo "## Known gaps"
    echo
    echo "$gaps"
  } >> "$WORK"
fi

mv -f "$WORK" "$OUTPUT"
chmod 644 "$OUTPUT"  # mktemp makes 0600; the committed index must stay world-readable for CI's sync

count=$(grep -c '^| ADR-' "$OUTPUT" || true)
echo "Wrote $count entries to $OUTPUT"
[ -n "$gaps" ] && printf '%b' "Gaps (not indexed):\n$gaps"
exit 0
